-- Run once in Supabase Dashboard > SQL Editor for this project.
-- Keep the Supabase secret key on the backend only.

create table if not exists public.sensor_readings (
    id bigint generated by default as identity primary key,
    user_id text not null,
    adxl_acc_x double precision not null,
    adxl_acc_y double precision not null,
    adxl_acc_z double precision not null,
    itg_gyro_x double precision not null,
    itg_gyro_y double precision not null,
    itg_gyro_z double precision not null,
    mma_acc_x double precision,
    mma_acc_y double precision,
    mma_acc_z double precision,
    heart_rate double precision,
    spo2 double precision,
    sugar_level double precision,
    latitude double precision,
    longitude double precision,
    recorded_at timestamptz not null default now()
);

create index if not exists sensor_readings_user_recorded_at_idx
    on public.sensor_readings (user_id, recorded_at desc);

create table if not exists public.notifications (
    id bigint generated by default as identity primary key,
    user_id text not null,
    notification_type text not null,
    recipient text,
    message text not null,
    severity text,
    risk_score integer,
    latitude double precision,
    longitude double precision,
    status text not null default 'pending',
    created_at timestamptz not null default now(),
    acknowledged_at timestamptz,
    resolved_at timestamptz
);

create index if not exists notifications_user_created_at_idx
    on public.notifications (user_id, created_at desc);

alter table public.sensor_readings enable row level security;
alter table public.notifications enable row level security;
